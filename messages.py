def language_key(language: str | None) -> str:
    """Short code for a supported language code; English when unknown."""
    short = str(language or DEFAULT_LANGUAGE).split("-")[0].strip().lower()
    return short if short in TABLES else "en"


def tr(language: str | None, key: str, **values: object) -> str:
    """Template for ``key`` in ``language``, English fallback, then ``key``."""
    short = language_key(language)
    template = TABLES[short].get(key)
    if template is None:
        template = EN.get(key) or HI.get(key)
    if template is None:
        return key
    if not values:
        return template
    try:
        return template.format(**values)
    except (KeyError, IndexError, ValueError):  # pragma: no cover - bad template
        return template
